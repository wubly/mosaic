#!/usr/bin/env python3
"""Builds the two static icon fonts and the codepoint table from the Material Symbols variable font.

Needs fonttools (`pip install fonttools`). Run from this directory after editing ICONS.
"""
import re
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools import subset

ICONS = """add album arrow_back arrow_forward audio_file auto_awesome bedtime bolt check check_box
check_box_outline_blank chevron_right clear_all close cloud_download create_new_folder delete
drag_indicator edit expand_less expand_more explore favorite folder folder_open fullscreen graphic_eq
history keyboard_arrow_down library_music link local_fire_department lock lyrics more_vert music_note
open_in_full open_in_new pause person picture_in_picture_alt play_arrow playlist_add playlist_play
queue_music refresh repeat repeat_one restart_alt search search_off sensors settings shuffle skip_next
skip_previous subtitles tune upload_file volume_down volume_off volume_up remove crop_square
filter_none album_fill sync warning""".split()
ICONS = [i for i in ICONS if i != "album_fill"]

codes = {}
for line in open("MaterialSymbolsRounded.codepoints"):
    name, cp = line.split()
    codes[name] = int(cp, 16)

for name, family, fill in (("filled", "Mosaic Symbols Filled", 1), ("outlined", "Mosaic Symbols Outlined", 0)):
    font = TTFont("MaterialSymbolsRounded.ttf")
    inst = instancer.instantiateVariableFont(font, {"FILL": fill, "GRAD": 0, "opsz": 24, "wght": 400})
    opts = subset.Options()
    opts.layout_features = []
    opts.name_IDs = ["*"]
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=[codes[i] for i in ICONS])
    sub.subset(inst)
    for rec in inst["name"].names:
        if rec.nameID in (1, 16):
            rec.string = family
        elif rec.nameID in (4, 6):
            rec.string = family.replace(" ", "")
    inst.save(f"MosaicSymbols-{name}.ttf")

with open("../../app/src/widgets/icon_codes.rs", "w") as out:
    out.write("// Generated by assets/fonts/make-icons.py; do not edit.\n")
    out.write("pub const CODES: &[(&str, char)] = &[\n")
    for i in ICONS:
        out.write(f'    ("{i}", \'\\u{{{codes[i]:x}}}\'),\n')
    out.write("];\n")
